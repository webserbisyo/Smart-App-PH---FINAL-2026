// Tidies what `drizzle-kit pull` writes so the mirror compiles and stays small (decision T116, Q9).
// Run through `pnpm --filter @smartapp/api db:pull`, never by hand. The SQL migrations stay the source of truth.
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..', 'src', 'db', 'generated');
const schemaPath = join(dir, 'schema.ts');

// We read tables with the plain query builder, so the relations file, the SQL snapshot and the meta folder go.
for (const name of readdirSync(dir)) {
  if (name !== 'schema.ts') rmSync(join(dir, name), { recursive: true, force: true });
}

let text = readFileSync(schemaPath, 'utf8');

// drizzle-kit 0.31 prints an empty text default as `.default(')`.
text = text.replaceAll(".default(')", ".default('')");

// Foreign keys to auth.users point at a table drizzle-kit does not declare; Drizzle ships it for Supabase.
if (text.includes('[users.id]')) {
  text = text.replaceAll('[users.id]', '[authUsers.id]');
  text = text.replace(
    /^(import [^\n]+\n)/,
    `$1import { authUsers } from 'drizzle-orm/supabase';\n`,
  );
}

// The bigint identity ceiling is the default anyway and cannot be a JS number without losing precision.
text = text.replaceAll(/,\s*maxValue:\s*9223372036854775807/g, '');

// Tables with only policies get `(table) => [...]` without using `table`, which lint rejects.
text = text
  .split('export const ')
  .map((chunk) =>
    chunk.includes('(table) => [') && !chunk.includes('table.')
      ? chunk.replace('(table) => [', '() => [')
      : chunk,
  )
  .join('export const ');

const header =
  '// Generated by `pnpm --filter @smartapp/api db:pull` from the local database. Do not edit by hand:\n' +
  '// change a migration in supabase/migrations, then pull again (decision T116, Q9).\n';

writeFileSync(schemaPath, header + text);
